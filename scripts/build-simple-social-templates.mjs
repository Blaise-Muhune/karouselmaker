/** Generate the additive social template seed. Existing templates and admin edits are preserved. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const designs = [
  ["Ink Headline", "headline", "#111827", "#FFFFFF", "left"],
  ["Paper Headline", "headline", "#FFF8ED", "#17202A", "center"],
  ["Cobalt Headline", "headline", "#1438A6", "#FFFFFF", "left"],
  ["Ink Body", "body", "#111827", "#FFFFFF", "left"],
  ["Paper Body", "body", "#FFF8ED", "#17202A", "left"],
  ["Forest Body", "body", "#12372A", "#FAF8F0", "left"],
];
const templates = designs.map(([name, mode, background, color, align], index) => ({
  id: `00000000-0000-4000-8000-${String(101 + index).padStart(12, "0")}`,
  name,
  category: "instagram",
  aspect_ratio: "4:5",
  config: {
    layout: "headline_center",
    safeArea: { top: 160, right: 160, bottom: 180, left: 112 },
    // Keep text inside the central square so 1:1, 4:5 and 9:16 all remain readable.
    // Retain both zones so an admin can re-enable either one later.
    textZones: [
      { id: "headline", enabled: mode === "headline", x: 112, y: 260, w: 808, h: 560,
        fontSize: 80, fontWeight: 800, lineHeight: 1.12, maxLines: 6, align, color, fontFamily: "system" },
      { id: "body", enabled: mode === "body", x: 112, y: 190, w: 808, h: 700,
        fontSize: 48, fontWeight: 600, lineHeight: 1.3, maxLines: 11, align: "left", color, fontFamily: "system" },
    ],
    overlays: {
      gradient: { enabled: false, direction: "bottom", strength: 0 },
      vignette: { enabled: false, strength: 0 },
    },
    chrome: { showSwipe: false, showCounter: false, counterStyle: "1/8", watermark: { enabled: false, position: "bottom_left" } },
    backgroundRules: { allowImage: false, defaultStyle: "none" },
    overlayShapes: [],
    defaults: {
      background: { style: "solid", color: background },
      meta: { background_color: background, show_counter: false, show_watermark: false,
        show_made_with: false, show_swipe: false, overlay_tint_opacity: 0,
        headline_highlight_style: "text", body_highlight_style: "text" },
    },
  },
}));
fs.writeFileSync(path.join(root, "lib/templates/simpleSocialTemplates.json"), JSON.stringify(templates, null, 2) + "\n");
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const rows = templates.map((t) => `(${quote(t.id)}, null, ${quote(t.name)}, ${quote(t.category)}, ${quote(t.aspect_ratio)}, ${quote(JSON.stringify(t.config))}::jsonb, true)`);
const sql = `-- Generated by scripts/build-simple-social-templates.mjs. Safe to rerun.\n-- Hiding affects discovery only; existing slides keep their template references.\nbegin;\nalter table public.templates add column if not exists is_hidden boolean not null default false;\n\ninsert into public.templates (id, user_id, name, category, aspect_ratio, config, is_locked)\nvalues\n${rows.join(",\n")}\non conflict (id) do nothing;\ncommit;\n`;
for (const target of ["azure/schema/006_template_visibility_and_social_set.sql", "supabase/migrations/065_template_visibility_and_social_set.sql"]) {
  fs.writeFileSync(path.join(root, target), sql);
}
console.log(`Generated ${templates.length} social templates and both database migrations.`);
